class PixelFont(ImageFont.ImageFont):
    def getlength(self, text, *args, **kwargs):
        self.validate(text)
        return len(text) * 6

    def getbbox(self, text, *args, **kwargs):
        return (0, 0, max(0, self.getlength(text) - 1), 7)

    @staticmethod
    def validate(text):
        if any(char not in GLYPHS for char in text):
            raise ValueError("Unsupported OLED character")

    def getmask(self, text, mode="", *args, **kwargs):
        self.validate(text)
        mask = Image.new("L", (max(1, len(text) * 6), 7))
        for index, char in enumerate(text):
            for y, row in enumerate(GLYPHS[char]):
                for x, value in enumerate(row):
                    if value == "1":
                        mask.putpixel((index * 6 + x, y), 255)
        return mask.im
